import pandas as pd
from sklearn.model_selection import train_test_split
from sklearn.preprocessing import StandardScaler


def load_data(file_path):
    print(f"Loading data from {file_path}...")
    df = pd.read_csv(file_path)
    return df


def clean_data(df):
    print("Cleaning data...")
    df = df.drop_duplicates()
    return df


def preprocess_data(df):
    print("Preprocessing data...")

    X = df.drop("target", axis=1)
    y = df["target"]

    continuous_features = [
        "age",
        "trestbps",
        "chol",
        "thalach",
        "oldpeak"
    ]

    scaler = StandardScaler()
    X[continuous_features] = scaler.fit_transform(
        X[continuous_features]
    )

    X_train, X_test, y_train, y_test = train_test_split(
        X,
        y,
        test_size=0.3,
        random_state=42,
        stratify=y
    )

    train_data = X_train.copy()
    train_data["target"] = y_train

    test_data = X_test.copy()
    test_data["target"] = y_test

    preprocessed_data = X.copy()
    preprocessed_data["target"] = y

    return train_data, test_data, preprocessed_data


def save_data(train_data, test_data, preprocessed_data):
    print("Saving processed data...")

    train_data.to_csv(
        "/content/heart-disease_train.csv",
        index=False
    )

    test_data.to_csv(
        "/content/heart-disease_test.csv",
        index=False
    )

    preprocessed_data.to_csv(
        "/content/heart-disease_preprocessed.csv",
        index=False
    )

    print("Data saved successfully.")


def run_preprocessing_pipeline(file_path):
    df = load_data(file_path)
    df = clean_data(df)

    train_data, test_data, preprocessed_data = preprocess_data(df)

    save_data(
        train_data,
        test_data,
        preprocessed_data
    )

    print("Preprocessing pipeline completed.")


# Jalankan pipeline
run_preprocessing_pipeline("/content/heart-disease.csv")